-- Players report their total key presses; a cron job freezes the ranking twice a day.
CREATE TABLE IF NOT EXISTS players (
  id          TEXT PRIMARY KEY,          -- random id generated by the app
  token_hash  TEXT NOT NULL,             -- SHA-256 of the secret token only that app knows
  name        TEXT NOT NULL,
  name_key    TEXT NOT NULL UNIQUE,      -- lower-cased name, for uniqueness
  char        TEXT NOT NULL DEFAULT 'yura',
  keys        INTEGER NOT NULL DEFAULT 0,
  created_at  INTEGER NOT NULL,
  updated_at  INTEGER NOT NULL
);

-- single row holding the last published ranking (JSON)
CREATE TABLE IF NOT EXISTS snapshot (
  k           INTEGER PRIMARY KEY CHECK (k = 1),
  data        TEXT NOT NULL,
  created_at  INTEGER NOT NULL
);
